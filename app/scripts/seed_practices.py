async def seed_practices() -> None:
    async with AsyncSessionFactory() as session:
        for item in PRACTICES:
            stmt = select(Practice).where(Practice.title == item["title"])
            result = await session.execute(stmt)
            existing = result.scalar_one_or_none()

            if existing is None:
                session.add(
                    Practice(
                        title=item["title"],
                        description=item["description"],
                    )
                )
            else:
                existing.description = item["description"]
                existing.created_at = existing.created_at or datetime.now(TZ)

        await session.commit()


if __name__ == "__main__":
    import asyncio

    asyncio.run(seed_practices())
